using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

/// <summary>
/// Menu:  Real Bingo ▸ Localization ▸ Build Devanagari Glyph Map
///
/// Reads Noto Sans Devanagari's `post` table and writes out every precomposed
/// glyph it contains, as a lookup the runtime can use.
///
/// WHY THIS WORKS
/// TextMeshPro has no Devanagari shaper, so it never runs the GSUB features
/// (rphf, half, cjct, pres…) that pick conjunct and reph glyphs — which is why
/// क्ष renders as क् + ष and पासवर्ड's र् never becomes a hook.
///
/// But the glyphs themselves ARE in the font, and Noto names them after the
/// Unicode sequence they represent:
///
///     uni0915094D0930  =  क + ् + र   ->  the क्र conjunct, one glyph
///     uni0938094D      =  स + ्        ->  the half form of स
///     uni0930094D      =  र + ्        ->  REPH, and its advance width is 0,
///                                          so it stacks above the glyph before it
///
/// Those are reachable by GLYPH INDEX even though no Unicode codepoint maps to
/// them. The runtime registers each one against a Private Use Area codepoint,
/// and the text preprocessor swaps the sequence for that codepoint before TMP
/// ever sees it. TMP then just draws a character, which is the one thing it
/// does reliably.
///
/// Output: Assets/Resources/Localization/devanagari_glyphmap.txt
///     <hex codepoints>\t<glyph index>
/// Generated at edit time rather than parsed at startup — the .ttf is 640 KB
/// and none of this changes unless the font does.
/// </summary>
public static class RBDevanagariGlyphMapBuilder
{
    private const string TtfPath = "Assets/Resources/Localization/Fonts/NotoSansDevanagari.ttf";
    private const string OutPath = "Assets/Resources/Localization/devanagari_glyphmap.txt";

    [MenuItem("Real Bingo/Localization/Build Devanagari Glyph Map")]
    public static void Build()
    {
        if (!File.Exists(TtfPath))
        {
            EditorUtility.DisplayDialog("Font missing", $"Expected {TtfPath}", "OK");
            return;
        }

        byte[] b = File.ReadAllBytes(TtfPath);

        Dictionary<string, int> tables = ReadTableDirectory(b);
        if (!tables.ContainsKey("post") || !tables.ContainsKey("hmtx") ||
            !tables.ContainsKey("hhea") || !tables.ContainsKey("head"))
        {
            Debug.LogError("[Localization] font is missing a table this needs (post/hmtx/hhea/head).");
            return;
        }

        string[] glyphNames = ReadPostNames(b, tables["post"]);
        if (glyphNames == null)
        {
            Debug.LogError("[Localization] this font has no glyph names (post table is not v2.0), " +
                           "so the sequences cannot be identified. Use a font that has them.");
            return;
        }

        int numHMetrics = U16(b, tables["hhea"] + 34);
        int hmtx = tables["hmtx"];

        var rows = new List<string>();
        int conjuncts = 0, halfForms = 0, zeroWidth = 0;

        for (int gid = 0; gid < glyphNames.Length; gid++)
        {
            string name = glyphNames[gid];
            if (string.IsNullOrEmpty(name) || !name.StartsWith("uni")) continue;

            // Regional alternates (.NEP / .SAN / .MAR) are deliberate variants
            // for other languages; taking them here would silently change the
            // letterforms for Hindi and Marathi.
            int dot = name.IndexOf('.');
            string hex = dot >= 0 ? name.Substring(3, dot - 3) : name.Substring(3);

            if (hex.Length < 8 || hex.Length % 4 != 0) continue;   // need 2+ codepoints
            if (dot >= 0) continue;

            bool valid = true;
            foreach (char c in hex)
                if (!Uri.IsHexDigit(c)) { valid = false; break; }
            if (!valid) continue;

            int advance = gid < numHMetrics ? U16(b, hmtx + gid * 4) : U16(b, hmtx + (numHMetrics - 1) * 4);

            rows.Add($"{hex.ToUpperInvariant()}\t{gid}\t{advance}");

            if (advance == 0) zeroWidth++;
            else if (hex.Length == 8) halfForms++;
            else conjuncts++;
        }

        var sb = new StringBuilder();
        sb.AppendLine("# Devanagari glyph map — generated by RBDevanagariGlyphMapBuilder.");
        sb.AppendLine("# <unicode sequence, hex>\\t<glyph index>\\t<advance width>");
        sb.AppendLine("# advance 0 means the glyph overlays the one before it (reph, marks).");
        sb.AppendLine($"# source: {TtfPath}");
        foreach (string r in rows) sb.AppendLine(r);

        Directory.CreateDirectory(Path.GetDirectoryName(OutPath));
        File.WriteAllText(OutPath, sb.ToString(), new UTF8Encoding(false));
        AssetDatabase.ImportAsset(OutPath);

        string msg = $"{rows.Count} precomposed glyphs written\n" +
                     $"   {halfForms} half forms (X + virama)\n" +
                     $"   {conjuncts} multi-consonant conjuncts\n" +
                     $"   {zeroWidth} zero-width (reph / marks)\n\n{OutPath}";

        Debug.Log("[Localization] " + msg.Replace("\n", " "));
        EditorUtility.DisplayDialog("Glyph map built", msg, "OK");
    }

    // ── TrueType reading ──────────────────────────────────────────────────────

    private static int U16(byte[] b, int o) => (b[o] << 8) | b[o + 1];
    private static int U32(byte[] b, int o) => (b[o] << 24) | (b[o + 1] << 16) | (b[o + 2] << 8) | b[o + 3];

    private static Dictionary<string, int> ReadTableDirectory(byte[] b)
    {
        var tables = new Dictionary<string, int>();
        int count = U16(b, 4);

        for (int i = 0; i < count; i++)
        {
            int rec = 12 + i * 16;
            string tag = Encoding.ASCII.GetString(b, rec, 4);
            tables[tag] = U32(b, rec + 8);
        }

        return tables;
    }

    /// <summary>
    /// post table v2.0: an index per glyph, then Pascal strings for the names
    /// that are not in the 258 standard Macintosh set.
    /// </summary>
    private static string[] ReadPostNames(byte[] b, int post)
    {
        if (U32(b, post) != 0x00020000) return null;

        int numGlyphs = U16(b, post + 32);
        var indices = new int[numGlyphs];
        for (int g = 0; g < numGlyphs; g++) indices[g] = U16(b, post + 34 + g * 2);

        var custom = new List<string>();
        int p = post + 34 + numGlyphs * 2;

        // The Pascal-string run is only as long as the indices reference; read
        // until every custom index is satisfied rather than to a table length
        // we would have to trust.
        int needed = 0;
        foreach (int ix in indices) if (ix >= 258) needed = Math.Max(needed, ix - 258 + 1);

        while (custom.Count < needed && p < b.Length)
        {
            int len = b[p];
            if (p + 1 + len > b.Length) break;
            custom.Add(Encoding.ASCII.GetString(b, p + 1, len));
            p += 1 + len;
        }

        var names = new string[numGlyphs];
        for (int g = 0; g < numGlyphs; g++)
        {
            int ix = indices[g];
            names[g] = (ix >= 258 && ix - 258 < custom.Count) ? custom[ix - 258] : null;
        }

        return names;
    }
}
